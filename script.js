// Scrollspy + Reveal Calibrat
const menuLinks = document.querySelectorAll('.nav nav a:not(.nav__cta)');
const sections = document.querySelectorAll('.section');

const scrollObserver = new IntersectionObserver((entries) => {
  entries.forEach(e => {
    if (e.isIntersecting) {
      e.target.classList.add('is-visible');
      const currentId = e.target.getAttribute('id');
      menuLinks.forEach(link => link.classList.remove('active'));
      const activeLink = document.querySelector(`.nav nav a[href="#${currentId}"]`);
      if (activeLink) activeLink.classList.add('active');
    }
  });
}, { 
  rootMargin: "-45% 0px -45% 0px",
  threshold: 0 
});

sections.forEach(sec => scrollObserver.observe(sec));

document.querySelectorAll('.hero__text, .hero__photo, .timeline li, .card').forEach(el => {
  el.classList.add('reveal');
  new IntersectionObserver((entries, self) => {
    entries.forEach(e => {
      if (e.isIntersecting) {
        e.target.classList.add('is-visible');
        self.unobserve(e.target);
      }
    });
  }, { threshold: 0.12 }).observe(el);
});

